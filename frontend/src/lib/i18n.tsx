type I18nContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string) => string
  formatDate: (value: string | Date | null | undefined, pattern?: 'short' | 'long' | 'datetime') => string
  formatRelativeTime: (value: string | Date) => string
}

const I18nContext = createContext<I18nContextValue>({
  locale: 'en',
  setLocale: () => undefined,
  t: (key) => key,
  formatDate: (value) => value ? new Date(value).toLocaleDateString('en-US') : '',
  formatRelativeTime: (value) => String(value),
})

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const subscribe = useCallback((callback: () => void) => {
    window.addEventListener('storage', callback)
    window.addEventListener('hackhub-locale-change', callback)
    return () => {
      window.removeEventListener('storage', callback)
      window.removeEventListener('hackhub-locale-change', callback)
    }
  }, [])
  const getLocale = useCallback((): Locale => {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    return stored === 'pt' || stored === 'en' ? stored : 'en'
  }, [])
  const locale = useSyncExternalStore(subscribe, getLocale, (): Locale => 'en')

  useEffect(() => {
    document.documentElement.lang = locale === 'pt' ? 'pt-PT' : 'en'
  }, [locale])

  const setLocale = useCallback((nextLocale: Locale) => {
    window.localStorage.setItem(STORAGE_KEY, nextLocale)
    window.dispatchEvent(new Event('hackhub-locale-change'))
  }, [])

  const t = useCallback((key: string) => locale === 'pt' ? (pt[key] || key) : key, [locale])
  const formatDate = useCallback((value: string | Date | null | undefined, pattern: 'short' | 'long' | 'datetime' = 'long') => {
    if (!value) return ''
    const date = typeof value === 'string' ? new Date(value) : value
    if (Number.isNaN(date.getTime())) return ''
    const options: Intl.DateTimeFormatOptions = pattern === 'short'
      ? { day: 'numeric', month: 'short', year: 'numeric' }
      : pattern === 'datetime'
        ? { day: 'numeric', month: 'long', year: 'numeric', hour: '2-digit', minute: '2-digit' }
        : { day: 'numeric', month: 'long', year: 'numeric' }
    return new Intl.DateTimeFormat(locale === 'pt' ? 'pt-PT' : 'en-US', options).format(date)
  }, [locale])

  const formatRelativeTime = useCallback((value: string | Date) => {
    const date = typeof value === 'string' ? new Date(value) : value
    if (Number.isNaN(date.getTime())) return ''
    const seconds = Math.round((date.getTime() - Date.now()) / 1000)
    const units: Array<[Intl.RelativeTimeFormatUnit, number]> = [
      ['year', 31536000], ['month', 2592000], ['week', 604800],
      ['day', 86400], ['hour', 3600], ['minute', 60], ['second', 1],
    ]
    const [unit, length] = units.find(([, unitLength]) => Math.abs(seconds) >= unitLength) || units[units.length - 1]
    return new Intl.RelativeTimeFormat(locale === 'pt' ? 'pt-PT' : 'en-US', { numeric: 'auto' }).format(Math.round(seconds / length), unit)
  }, [locale])

  const value = useMemo(() => ({ locale, setLocale, t, formatDate, formatRelativeTime }), [locale, setLocale, t, formatDate, formatRelativeTime])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}

export function translateCurrent(value: unknown): string {
  if (typeof window === 'undefined') return typeof value === 'string' ? value : 'Something went wrong. Please try again.'
  const portuguese = window.localStorage.getItem(STORAGE_KEY) === 'pt'
  if (Array.isArray(value)) {
    const messages = value.map((item) => {
      if (item && typeof item === 'object' && 'msg' in item) return translateCurrent(String(item.msg))
      return translateCurrent(item)
    }).filter(Boolean)
    const uniqueMessages = Array.from(new Set(messages))
    return uniqueMessages.length
      ? `${portuguese ? 'Revê os campos do formulário:' : 'Review the form fields:'} ${uniqueMessages.join(' ')}`
      : (portuguese ? 'Revê os campos do formulário e tenta novamente.' : 'Review the form fields and try again.')
  }
  if (value && typeof value === 'object' && 'detail' in value) return translateCurrent(value.detail)
  if (typeof value !== 'string') return portuguese ? 'Ocorreu um erro. Tenta novamente.' : 'Something went wrong. Please try again.'
  const key = value
  if (!portuguese) return key
  if (pt[key]) return pt[key]

  const teamTitle = key.match(/^Team Invitation: (.+)$/)
  if (teamTitle) return `Convite para a equipa: ${teamTitle[1]}`
  const teamInvite = key.match(/^You have been invited to join team '(.+)'$/)
  if (teamInvite) return `Foste convidado para a equipa “${teamInvite[1]}”.`
  const eventStatus = key.match(/^Event status changed to (.+)$/)
  if (eventStatus) {
    const status = eventStatus[1]
    const translatedStatus: Record<string, string> = {
      draft: 'rascunho',
      published: 'publicado',
      in_progress: 'em curso',
      closed: 'encerrado',
    }
    return `Estado do evento alterado para ${translatedStatus[status] || status}.`
  }
  if (/^Team already has maximum \d+ members$/.test(key)) {
    return 'A equipa já atingiu o número máximo de membros.'
  }
  if (/^Criterion .+ does not belong to this project$/.test(key)) {
    return 'O critério indicado não pertence a este projeto.'
  }
  if (/^Score exceeds the maximum for criterion .+$/.test(key)) {
    return 'A pontuação excede o máximo permitido para este critério.'
  }
  if (key === 'Field required') return 'Campo obrigatório.'
  if (key === 'Input should be a valid email address') return 'Introduz um endereço de email válido.'
  if (/^String should have at least \d+ characters$/.test(key)) return 'O texto é demasiado curto.'
  if (/^String should have at most \d+ characters$/.test(key)) return 'O texto é demasiado longo.'
  if (/^Input should be greater than or equal to .+$/.test(key)) return 'O valor está abaixo do mínimo permitido.'
  if (/^Input should be less than or equal to .+$/.test(key)) return 'O valor excede o máximo permitido.'
  if (key.startsWith('Input should be a valid URL')) return 'Introduz um URL válido.'
  if (key.startsWith('Input should be a valid integer')) return 'Introduz um número inteiro válido.'
  if (key.startsWith('Input should be a valid number')) return 'Introduz um número válido.'
  if (key.startsWith('Input should be a valid string')) return 'Introduz um texto válido.'
  return 'Ocorreu um erro. Tenta novamente.'
}

export function eventStatusText(status: string) {
  const labels: Record<string, string> = {
    draft: 'Draft',
    published: 'Registration open',
    in_progress: 'In progress',
    closed: 'Completed',
  }
  return labels[status] || status
}

export function LocalizedText({ text }: { text: string }) {
  const { t } = useI18n()
  return <>{t(text)}</>
}

export function LocalizedDate({ value, pattern = 'long' }: { value: string | Date | null | undefined; pattern?: 'short' | 'long' | 'datetime' }) {
  const { formatDate } = useI18n()
  return <>{formatDate(value, pattern)}</>
}

export function LocalizedRelativeTime({ value }: { value: string | Date }) {
  const { formatRelativeTime } = useI18n()
  return <>{formatRelativeTime(value)}</>
}
